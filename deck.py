BASIS = {"+": "card", "-": "card", "I": "inertia", "R": "reversal", "C": "coin"}


def build_deck():
    deck = []
    for i, (name, meaning, codes) in enumerate(MAJORS):
        deck.append({"name": name, "numeral": ROMAN[i], "arcana": "major", "suit": "",
                     "image": f"major_{i:02d}.jpg", "meaning": meaning, "codes": codes})
    for suit, (file, _) in SUITS.items():
        for j, (meaning, codes) in enumerate(MINORS[suit]):
            deck.append({"name": f"{RANKS[j]} {suit}", "numeral": RANK_NUM[j], "arcana": "minor", "suit": suit,
                         "image": f"{file}_{j + 1:02d}.jpg", "meaning": meaning, "codes": codes})
    assert len(deck) == 78 and all(len(c["codes"]) == 3 and set(c["codes"]) <= set("+-IRC") for c in deck)
    return deck


def draw(n):
    """Честный случайный расклад без повторов (криптостойкий ГСЧ). Все карты — в прямом положении."""
    out = []
    for c in secrets.SystemRandom().sample(build_deck(), n):
        c = dict(c, reversed=False)
        out.append(c)
    return out


def direction(card, asset, last_chg):
    """Направление карты для рынка: (+1/-1, основание). last_chg — последнее дневное изменение рынка в %."""
    code = card["codes"][ASSET_ORDER.index(asset)]
    last = 1 if (last_chg or 0) >= 0 else -1
    if code == "+":
        d = 1
    elif code == "-":
        d = -1
    elif code == "I":
        d = last
    elif code == "R":
        d = -last
    else:  # "C"
        d = secrets.choice((1, -1))
    return d, BASIS[code]
