@dataclass
class Card:
    name: str
    numeral: str
    arcana: str          # "major" / "minor"
    suit: str            # для старших — ""
    polarity: int
    upright: str
    reversed_meaning: str
    image: str = ""      # файл в assets/cards (Райдер–Уэйт–Смит, изд. 1909, общественное достояние)


def build_deck():
    deck = []
    for i, (name, pol, up, rev) in enumerate(MAJORS):
        deck.append(Card(name, ROMAN[i], "major", "", pol, up, rev, f"major_{i:02d}.jpg"))
    for suit, theme in SUITS.items():
        for j, rank in enumerate(RANKS):
            up, rev = RANK_MEANING[rank]
            num = ["Т", "2", "3", "4", "5", "6", "7", "8", "9", "10", "П", "Р", "Д", "К"][j]
            deck.append(Card(f"{rank} {suit}", num, "minor", suit, MINOR_POLARITY[suit][j],
                             f"{up} — в сфере: {theme}", f"{rev} — в сфере: {theme}",
                             f"{SUIT_FILE[suit]}_{j + 1:02d}.jpg"))
    assert len(deck) == 78
    return deck


def draw(n, reversal_chance=0.3):
    """Честный случайный расклад без повторов (криптостойкий ГСЧ)."""
    rng = secrets.SystemRandom()
    cards = rng.sample(build_deck(), n)
    out = []
    for c in cards:
        is_rev = rng.random() < reversal_chance
        d = asdict(c)
        d["reversed"] = is_rev
        d["effective_polarity"] = -c.polarity if is_rev else c.polarity
        d["meaning"] = c.reversed_meaning if is_rev else c.upright
        out.append(d)
    return out
